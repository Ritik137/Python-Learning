# What is variables?
# Variables are containers for storing data values.
# 2. If variable is created u first assign a value to it
# 3. You can get a datatype of a variable with the type()
# 4. Variable names are case-sensitive,

# Rules of a variable:
# 1. A variable name must start with a letter or the underscore character.
# 2. A variable name cannot start with a number.
# 3. A variable name can only contain alphaNumeric characters and underscores (A-z, 0-9, and _ ).
# 4. A variable name cannot contain any of the python keywords.

# Variables are three types:
# 1. CamelCase   : Each word except the first, starts with a capital letter. Example: myVariableName
# 2. PascalCase : Each word starts with a capotal letter. Example: MyVariableName  
# 3. snakeCase : Each word is separated by an underscore character. Example: my_variable_name
